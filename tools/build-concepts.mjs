// Build src/lib/concepts.js: curated concept defs + top verse links computed
// from the shipped corpora via the real search index (no hand-made links).
// Usage: node tools/build-concepts.mjs
import { readFile, writeFile } from "node:fs/promises";
import { buildIndex, search } from "../src/lib/search.js";

const SOURCES = [
  ["corpus/durgasaptashati.json", "Durgāsaptaśatī"],
  ["corpus/tantraloka-ch1.json", "Tantrāloka, Ch. 1"],
];

const passages = [];
const commentaries = [];
const SCRIP = [];
for (const [path, fallbackTitle] of SOURCES) {
  const doc = JSON.parse(await readFile(path, "utf-8"));
  const title = doc.scriptures[0]?.title || fallbackTitle;
  SCRIP.push([doc.scriptures[0]?.id || path, title]);
  passages.push(...doc.passages);
  commentaries.push(...doc.commentaries);
}

const byPassage = new Map(passages.map((p) => [p.id, p]));
const byScripture = new Map(SCRIP);
const idx = buildIndex(passages, commentaries);
const src = JSON.parse(await readFile("tools/concepts-src.json", "utf-8"));

const CONCEPTS = src.map((c) => {
  const seen = new Map();
  for (const q of [c.term, c.iast]) {
    for (const r of search(idx, q, {})) {
      if (!seen.has(r.pid)) seen.set(r.pid, r);
    }
  }
  const links = [...seen.values()]
    .sort((a, b) => b.score - a.score)
    .slice(0, 5)
    .map((r) => {
      const p = byPassage.get(r.pid);
      return {
        scripture: byScripture.get(p.scriptureId) || p.scriptureId,
        section: p.section || "",
        ordinal: p.ordinal,
      };
    });
  return { ...c, links };
});

await writeFile(
  "src/lib/concepts.js",
  `/** Generated by tools/build-concepts.mjs — do not hand-edit. Links are computed from the shipped corpora. */\nexport const CONCEPTS = ${JSON.stringify(CONCEPTS)};\n`
);
const linked = CONCEPTS.filter((c) => c.links.length > 0).length;
console.log(`concepts: ${CONCEPTS.length}, with links: ${linked}`);
for (const c of CONCEPTS) {
  if (c.links.length === 0) console.log("UNLINKED:", c.term);
}
